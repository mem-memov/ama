#include "../common.c"
#include "codegen/native.h"

static void declare_native_interface(void) {
    Token zero = {.type = TOKEN_LITERAL, .lexeme = "0"};
    Token alias_path = {.type = TOKEN_MODULE_PATH, .lexeme = ".sys.io.print"};
    Symbol* value = add_declarative_symbol(symbols, "math/scale", "value", SYMBOL_PARAMETER, zero, &error);
    Symbol* factor = add_declarative_symbol(symbols, "math/scale", "factor", SYMBOL_PARAMETER, zero, &error);
    Symbol* result = add_declarative_symbol(symbols, "math/scale", "answer", SYMBOL_RESULT, zero, &error);
    Symbol* alias = add_declarative_symbol(symbols, "math/scale", "print", SYMBOL_MODULE_ALIAS, alias_path, &error);
    assert(value && factor && result && alias);
}

static void it_builds_value_parameters_and_pointer_results_in_declaration_order(void) {
    setup_test();
    declare_native_interface();
    bool emitted = emit_native_header(output, symbols, "math/scale", &error);
    assert(emitted);
    assert_stream_equals(output,
        "/* Generated by Ama; do not edit. */\n"
        "#ifndef AMA_NATIVE_HEADER_ama_native_math_scale\n#define AMA_NATIVE_HEADER_ama_native_math_scale\n"
        "#include <stddef.h>\n\n"
        "void ama_native_math_scale(size_t parameter_value, size_t parameter_factor, size_t* result_answer);\n"
        "\n#endif\n");
    destroy_test();
}

static void it_passes_every_result_address_through_the_wrapper(void) {
    setup_test();
    declare_native_interface();
    bool emitted = emit_native_wrapper(&emitter, "math/scale", &error);
    assert(emitted);
    assert_stream_equals(output,
        "#include \"ama_native_math_scale.h\"\n\n"
        "void module_math_scale(void) {\n"
        "    ama_native_math_scale(symbol_0, symbol_1, &symbol_2);\n}\n\n");
    destroy_test();
}

static void it_uses_void_for_an_empty_native_signature(void) {
    setup_test();
    bool emitted = emit_native_header(output, symbols, "nothing", &error);
    assert(emitted);
    assert_stream_equals(output,
        "/* Generated by Ama; do not edit. */\n"
        "#ifndef AMA_NATIVE_HEADER_ama_native_nothing\n#define AMA_NATIVE_HEADER_ama_native_nothing\n"
        "#include <stddef.h>\n\nvoid ama_native_nothing(void);\n\n#endif\n");
    destroy_test();
}

static void it_prefixes_c_keywords_used_as_ama_parameter_names(void) {
    setup_test();
    Token zero = {.type = TOKEN_LITERAL, .lexeme = "0"};
    Symbol* keyword = add_declarative_symbol(symbols, "keyword", "switch", SYMBOL_PARAMETER, zero, &error);
    assert(keyword != NULL);
    bool emitted = emit_native_header(output, symbols, "keyword", &error);
    assert(emitted);
    assert_stream_equals(output,
        "/* Generated by Ama; do not edit. */\n"
        "#ifndef AMA_NATIVE_HEADER_ama_native_keyword\n#define AMA_NATIVE_HEADER_ama_native_keyword\n"
        "#include <stddef.h>\n\nvoid ama_native_keyword(size_t parameter_switch);\n\n#endif\n");
    destroy_test();
}

static void it_reports_names_that_c_cannot_represent_portably(void) {
    setup_test();
    char name[MAX_FILE_PATH_LENGTH];
    bool named = native_function_name("math/invalid-name", name, sizeof(name), &error);
    assert(!named && error.error_code == ERROR_INVALID);
    error_clear(&error);
    Token zero = {.type = TOKEN_LITERAL, .lexeme = "0"};
    Symbol* unicode = add_declarative_symbol(symbols, "unicode", "\u03bbvalue", SYMBOL_PARAMETER, zero, &error);
    assert(unicode != NULL);
    bool valid = validate_native_signature(symbols, "unicode", &error);
    assert(!valid && error.error_code == ERROR_INVALID);
    destroy_test();
}

void run(void) {
    it_builds_value_parameters_and_pointer_results_in_declaration_order();
    it_passes_every_result_address_through_the_wrapper();
    it_uses_void_for_an_empty_native_signature();
    it_prefixes_c_keywords_used_as_ama_parameter_names();
    it_reports_names_that_c_cannot_represent_portably();
}

int main(void) {
    run();
    printf("unit/codegen/native: %d test(s) passed\n", test_count);
    return EXIT_SUCCESS;
}
