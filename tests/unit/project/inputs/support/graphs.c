/**
 * @file
 * @brief Prove fixed-point invalidation against exhaustive independent finite graph reachability.
 */

/** Construct an identical topology in either snapshot, changing only the selected source payload. */
static void graph(ProjectInputs *inputs, unsigned mask, size_t seed, const char *payload) {
    ProjectInput *nodes[3];
    const char *names[] = {"a", "b", "c"};
    for (size_t index = 0; index < 3; index++) { nodes[index] = put(inputs, PROJECT_INPUT_MODULE, names[index], ""); }
    ProjectInput *file = put(inputs, PROJECT_INPUT_FILE, "source", payload);
    depend(inputs, nodes[seed], file);
    for (size_t from = 0; from < 3; from++) {
        for (size_t to = 0; to < 3; to++) {
            if ((mask & (1u << (from * 3 + to))) != 0) { depend(inputs, nodes[from], nodes[to]); }
        }
    }
    ProjectInput *generated = put(inputs, PROJECT_INPUT_GENERATED, "assembly", "same generated bytes");
    depend(inputs, generated, nodes[2]);
    project_inputs_seal(inputs);
}
/** Exhaust all directed graphs including cycles/self edges; Floyd-Warshall supplies an independent closure oracle. */
static void it_matches_independent_reachability_for_every_three_node_graph_and_changed_seed(void) {
    setup_test();
    const char *names[] = {"a", "b", "c"};
    for (unsigned mask = 0; mask < 512; mask++) {
        bool reachable[3][3];
        for (size_t from = 0; from < 3; from++) {
            for (size_t to = 0; to < 3; to++) {
                reachable[from][to] = from == to || (mask & (1u << (from * 3 + to))) != 0;
            }
        }
        for (size_t middle = 0; middle < 3; middle++) {
            for (size_t from = 0; from < 3; from++) {
                for (size_t to = 0; to < 3; to++) {
                    reachable[from][to] |= reachable[from][middle] && reachable[middle][to];
                }
            }
        }
        for (size_t seed = 0; seed < 3; seed++) {
            ProjectInputs before, after;
            project_inputs_init(&before, sources.allocator);
            project_inputs_init(&after, sources.allocator);
            graph(&before, mask, seed, "old");
            graph(&after, mask, seed, "new");
            size_t count = allocation_count;
            SourceStatus status = project_inputs_compare(&after, &before);
            assert(status == SOURCE_OK && allocation_count == count);
            for (size_t vertex = 0; vertex < 3; vertex++) {
                assert(changed(&after, PROJECT_INPUT_MODULE, names[vertex]) == reachable[vertex][seed]);
            }
            assert(changed(&after, PROJECT_INPUT_GENERATED, "assembly") == reachable[2][seed]);
            status = project_inputs_compare(&after, &after);
            assert(status == SOURCE_OK);
            assert(!changed(&after, PROJECT_INPUT_FILE, "source"));
            project_inputs_destroy(&after);
            project_inputs_destroy(&before);
        }
    }
    destroy_test();
}

/** Repeated exact inputs/edges allocate nothing; collisions, foreign owners and sealed mutation preserve prior output. */
static void it_deduplicates_keys_edges_and_rejects_conflicting_or_closed_mutation(void) {
    setup_test();
    ProjectInputs inputs, foreign;
    project_inputs_init(&inputs, sources.allocator);
    project_inputs_init(&foreign, sources.allocator);
    ProjectInput *file = put(&inputs, PROJECT_INPUT_FILE, "same", "bytes");
    ProjectInput *configuration = put(&inputs, PROJECT_INPUT_CONFIGURATION, "same", "bytes");
    assert(file != configuration);
    depend(&inputs, configuration, file);
    size_t count = allocation_count;
    ProjectInput *repeat = put(&inputs, PROJECT_INPUT_FILE, "same", "bytes");
    depend(&inputs, configuration, file);
    assert(repeat == file && allocation_count == count);
    SourceStatus status = project_inputs_put(&inputs, PROJECT_INPUT_FILE, "same",
        (const unsigned char *)"other", 5, &repeat);
    assert(status == SOURCE_INVALID_ARGUMENT && repeat == file);
    ProjectInput *other = put(&foreign, PROJECT_INPUT_MODULE, "foreign", "");
    status = project_inputs_depend(&inputs, file, other);
    assert(status == SOURCE_INVALID_ARGUMENT);
    bool output = true;
    assert(!project_inputs_changed(&inputs, PROJECT_INPUT_FILE, "same", &output) && output);
    status = project_inputs_compare(&inputs, NULL);
    assert(status == SOURCE_INVALID_ARGUMENT);
    project_inputs_seal(&inputs);
    status = project_inputs_put(&inputs, PROJECT_INPUT_FILE, "new", NULL, 0, &repeat);
    assert(status == SOURCE_INVALID_ARGUMENT && repeat == file);
    status = project_inputs_depend(&inputs, file, configuration);
    assert(status == SOURCE_INVALID_ARGUMENT);
    status = project_inputs_compare(&inputs, NULL);
    assert(status == SOURCE_OK && changed(&inputs, PROJECT_INPUT_CONFIGURATION, "same"));
    project_inputs_destroy(&foreign);
    project_inputs_destroy(&inputs);
    destroy_test();
}

/** Binary payloads and dependency membership are exact; an unrelated new input cannot invalidate old consumers. */
static void it_detects_dependency_membership_and_embedded_zero_payload_changes(void) {
    setup_test();
    ProjectInputs before;
    project_inputs_init(&before, sources.allocator);
    const unsigned char original[] = {'a', 0, 'b'};
    ProjectInput *old_file = NULL;
    SourceStatus status = project_inputs_put(&before, PROJECT_INPUT_FILE, "x", original, 3, &old_file);
    assert(status == SOURCE_OK);
    ProjectInput *old_a = put(&before, PROJECT_INPUT_MODULE, "a", "");
    ProjectInput *old_b = put(&before, PROJECT_INPUT_MODULE, "b", "");
    depend(&before, old_a, old_file);
    depend(&before, old_b, old_file);
    project_inputs_seal(&before);
    for (size_t change = 0; change < 5; change++) {
        ProjectInputs after;
        project_inputs_init(&after, sources.allocator);
        unsigned char payload[] = {'a', 0, change == 2 ? 'c' : 'b'};
        ProjectInput *file = NULL;
        status = project_inputs_put(&after, PROJECT_INPUT_FILE, "x", payload, 3, &file);
        assert(status == SOURCE_OK);
        ProjectInput *a = put(&after, PROJECT_INPUT_MODULE, "a", "");
        ProjectInput *b = put(&after, PROJECT_INPUT_MODULE, "b", "");
        if (change == 1) {
            ProjectInput *added = put(&after, PROJECT_INPUT_FILE, "y", "new");
            depend(&after, a, added);
        } else if (change != 3) {
            depend(&after, a, file);
        }
        if (change == 4) { (void)put(&after, PROJECT_INPUT_FILE, "unrelated", "new"); }
        depend(&after, b, file);
        project_inputs_seal(&after);
        status = project_inputs_compare(&after, &before);
        assert(status == SOURCE_OK);
        assert(changed(&after, PROJECT_INPUT_MODULE, "a") == (change >= 1 && change <= 3));
        assert(changed(&after, PROJECT_INPUT_MODULE, "b") == (change == 2));
        project_inputs_destroy(&after);
    }
    project_inputs_destroy(&before);
    destroy_test();
}
