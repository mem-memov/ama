/** @file
 * @brief Verify documented entry/library field rewriting and safe explicit output invalidation plans.
 */
/** Library names/flags/comments stay exact while the entry, export and explicit dependency referents follow the move. */
static void it_prepares_explicit_settings_and_generated_output_invalidations(void) {
    setup("staged-settings");
    package("project", "fixture"); folder("project/packages/test/fixture/v1.0.0/src/old"); folder("artifacts");
    file("project/packages/test/fixture/v1.0.0/src/old/a","@!\n");
    file("project/packages/test/fixture/v1.0.0/src/old/helper.c","/* Opaque dependency. */\n");
    file("project/packages/test/fixture/v1.0.0/src/old/generated.bin","old generated bytes");
    file("artifacts/cache.bin","old external cache");
    const char *configuration = source_arena_join(&fixture_paths,
        "ama-library | 1\ncomponent | example.component\nabi | ama-c-1\ntarget | test\ncalling-convention | c\n# .old.a remains comment\nexport | run | /test/fixture/v1.0.0/src/old/a | entry,resume,read\nc-flag | -DVALUE=.old.a\ndependency-file | ",
        path("project/packages/test/fixture/v1.0.0/src/old/helper.c"),"\n");
    assert(configuration != NULL);
    file("project/packages/test/fixture/v1.0.0/src/old/build.library",configuration);
    ModuleRoot root = {.path=path("project"),.kind=MODULE_ROOT_PROJECT};
    RelocationRequest request = {&root,1,path("project/packages/test/fixture/v1.0.0/src/old"),path("project/packages/test/fixture/v1.0.0/src/new"),NULL};
    assert(relocation_preview_build(&preview,&request));
    RelocationReferences references;
    relocation_references_init(&references,sources.allocator);
    assert(relocation_references_build(&references,&preview));
    const char *configurations[] = {path("project/packages/test/fixture/v1.0.0/src/old/build.library")};
    const char *outputs[] = {path("artifacts/cache.bin"),path("artifacts/missing.bin"),path("project/packages/test/fixture/v1.0.0/src/old/generated.bin")};
    RelocationStagingRequest settings = {.references=&references,.entry="/test/fixture/v1.0.0/src/old/a",
        .library_configurations=configurations,.library_configuration_count=1,
        .generated_outputs=outputs,.generated_output_count=3};
    RelocationStaging staging;
    relocation_staging_init(&staging,sources.allocator);
    bool built = relocation_staging_build(&staging,&settings);
    if (!built) { fprintf(stderr,"Settings %d: %s\n",staging.status,staging.error.message == NULL ? "No diagnostic" : staging.error.message); }
    assert(built && staging.ready && strcmp(staging.entry,"/test/fixture/v1.0.0/src/new/a") == 0);
    const RelocationStagedFile *dependency = captured(&staging,"/helper.c");
    assert(dependency != NULL && dependency->protected_input);
    const char *expected_dependency = source_arena_join(&fixture_paths,preview.destination,"/","helper.c");
    assert(expected_dependency != NULL && strcmp(dependency->after,expected_dependency) == 0);
    const char *expected = source_arena_join(&fixture_paths,
        "ama-library | 1\ncomponent | example.component\nabi | ama-c-1\ntarget | test\ncalling-convention | c\n# .old.a remains comment\nexport | run | /test/fixture/v1.0.0/src/new/a | entry,resume,read\nc-flag | -DVALUE=.old.a\ndependency-file | ",
        dependency->after,"\n");
    assert(expected != NULL);
    exact(staging.configurations->file->replacement,expected);
    assert(staging.configurations->before.exports->type != staging.configurations->after.exports->type);
    assert(strcmp(staging.configurations->after.exports->type->module->source->logical_path,"/test/fixture/v1.0.0/src/new/a") == 0);
    size_t invalidations = 0, absent = 0;
    for (const RelocationInvalidation *item = staging.invalidations; item != NULL; item = item->next) {
        invalidations++;
        if (!item->existed) { absent++; }
    }
    assert(invalidations == 3 && absent == 1);
    struct stat metadata;
    assert(lstat(path("artifacts/cache.bin"),&metadata) == 0);
    assert(lstat(path("project/packages/test/fixture/v1.0.0/src/old/generated.bin"),&metadata) == 0);
    untouched(&request);
    relocation_staging_destroy(&staging);

    const char *bad_outputs[] = {path("project/packages/test/fixture/v1.0.0/src/old/a")};
    settings.generated_outputs = bad_outputs;
    settings.generated_output_count = 1;
    relocation_staging_init(&staging,sources.allocator);
    assert(!relocation_staging_build(&staging,&settings) && staging.status == RELOCATION_INVALID_PATH);
    relocation_staging_destroy(&staging);
    bad_outputs[0] = path("project");
    relocation_staging_init(&staging,sources.allocator);
    assert(!relocation_staging_build(&staging,&settings) && staging.status == RELOCATION_INVALID_PATH);
    relocation_staging_destroy(&staging);
    bad_outputs[0] = path("project/packages/test/fixture/v1.0.0/src/old/helper.c");
    relocation_staging_init(&staging,sources.allocator);
    assert(!relocation_staging_build(&staging,&settings) && staging.status == RELOCATION_INVALID_PATH);
    relocation_staging_destroy(&staging);
    const char *overlap[] = {path("artifacts"),path("artifacts/cache.bin")};
    settings.generated_outputs = overlap;
    settings.generated_output_count = 2;
    relocation_staging_init(&staging,sources.allocator);
    assert(!relocation_staging_build(&staging,&settings) && staging.status == RELOCATION_INVALID_PATH);
    relocation_staging_destroy(&staging);
    settings.generated_output_count = 0;
    settings.entry = "/test/fixture/v1.0.0/src/missing";
    relocation_staging_init(&staging,sources.allocator);
    assert(!relocation_staging_build(&staging,&settings) && staging.status == RELOCATION_INVALID_REFERENCE);
    relocation_staging_destroy(&staging);
    untouched(&request);
    relocation_references_destroy(&references);
    finish();
}
