/**
 * @file
 * @brief Regenerate maximal immutable XID ranges from the pinned Unicode input.
 *
 * [SRC-03](../../spec/language/source-and-names.md#src-03) requires exact Unicode
 * word membership. This offline finite-domain conversion never uses host tables;
 * complete multiword-name syntax remains separate from individual word properties.
 */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define SCALAR_LIMIT 0x110000U

/** Union the pinned edition's recognized XID ranges into caller-owned bitmaps.
 * Non-XID properties/comments are ignored; reversed/out-of-domain ranges and read
 * errors fail. Caller owns file closure and tables; line scratch is always freed.
 */
static bool read_properties(FILE *input, unsigned char *start, unsigned char *continuation) {
    char *line = NULL;
    size_t capacity = 0;
    bool valid = true;
    while (getline(&line, &capacity, input) >= 0) {
        unsigned int first;
        unsigned int last;
        char property[64];
        int fields = sscanf(line, "%x..%x ; %63s", &first, &last, property);
        if (fields != 3) {
            fields = sscanf(line, "%x ; %63s", &first, property);
            if (fields != 2) {
                continue;
            }
            last = first;
        }
        unsigned char *table = strcmp(property, "XID_Start") == 0 ? start
            : strcmp(property, "XID_Continue") == 0 ? continuation : NULL;
        if (table == NULL) {
            continue;
        }
        if (first > last || last >= SCALAR_LIMIT) {
            valid = false;
            break;
        }
        memset(table + first, 1, last - first + 1);
    }
    free(line);
    return valid && !ferror(input);
}

/** Emit maximal increasing nonzero runs over the complete finite scalar domain.
 * stdout errors are checked by main after emission; no runtime table sampling.
 */
static void emit_ranges(const char *name, const unsigned char *table) {
    printf("static const UnicodeRange %s[] = {\n", name);
    for (uint32_t scalar = 0; scalar < SCALAR_LIMIT; scalar++) {
        if (table[scalar] == 0) {
            continue;
        }
        uint32_t first = scalar;
        while (scalar + 1 < SCALAR_LIMIT && table[scalar + 1] != 0) {
            scalar++;
        }
        printf("    {0x%Xu, 0x%Xu},\n", first, scalar);
    }
    puts("};");
}

/** Borrow exactly one input filename, check its edition and own the input stream
 * and two bitmaps. Emit only after successful read/close; report stdout errors
 * through exit status. Output is deterministic for fixed pinned input.
 */
int main(int argument_count, char **arguments) {
    if (argument_count != 2) {
        return EXIT_FAILURE;
    }
    FILE *input = fopen(arguments[1], "rb");
    if (input == NULL) {
        return EXIT_FAILURE;
    }
    unsigned char *tables = calloc(SCALAR_LIMIT, 2);
    char header[128];
    bool valid = tables != NULL && fgets(header, sizeof(header), input) != NULL
        && strcmp(header, "# DerivedCoreProperties-17.0.0.txt\n") == 0;
    if (valid) {
        valid = read_properties(input, tables, tables + SCALAR_LIMIT);
    }
    int closed = fclose(input);
    if (valid && closed == 0) {
        puts("/* Unicode 17.0.0; generated by tools/unicode/generate.c.");
        puts(" * Unicode License V3: third_party/unicode/LICENSE.txt. */");
        puts("/**");
        puts(" * @file");
        puts(" * @brief Pinned Unicode 17.0.0 XID ranges, regenerated offline without host Unicode state.");
        puts(" * [SRC-03](../../../spec/language/source-and-names.md#src-03) requires exact word membership.");
        puts(" * Sorted disjoint maximal closed ranges support identifier.c's exact binary search.");
        puts(" * Provenance and license remain in third_party/unicode; do not hand-edit these ranges.");
        puts(" */");
        emit_ranges("xid_start", tables);
        emit_ranges("xid_continue", tables + SCALAR_LIMIT);
    }
    free(tables);
    /* A short table can remain entirely buffered. Check the final flush before
     * reporting success, rather than relying on process-exit flushing status. */
    bool written = fflush(stdout) == 0 && !ferror(stdout);
    return valid && closed == 0 && written ? EXIT_SUCCESS : EXIT_FAILURE;
}
