#include "codegen/internal.h"

bool codegen_emit_host_begin(NativeScaffold *scaffold, FILE *output) {
    return fprintf(output,
            "/* One host execution function; Ama bodies are labels below. */\n"
            "static AmaProjectHost *ama_project_owner;\n"
            "AmaStatus ama_project_dispose(AmaProjectHost *host) {\n"
            "    if(host->executing) return ama_status_make(AMA_BUSY,NULL,0);\n"
            "    if(host->disposed) return host->status;\n"
            "    if(host->initialized) {\n"
            "        host->status=ama_program_stop(&host->program,host->root,host->status);\n"
            "        if(host->status.code!=AMA_OK && !host->program.failure_reported) ama_program_report(&host->program,host->status);\n"
            "    }\n"
            "    host->disposed=true; if(ama_project_owner==host) ama_project_owner=NULL;\n"
            "    return host->status;\n}\n"
            "AmaProjectResult ama_project_execute(AmaProjectHost *host, AmaAccessMode mode) {\n"
            "    if(host->executing || (ama_project_owner!=NULL && ama_project_owner!=host))\n"
            "        return (AmaProjectResult){AMA_PROJECT_FAILED,ama_status_make(AMA_BUSY,NULL,0)};\n"
            "    if(host->disposed || (mode!=AMA_ACCESS_ENTRY && mode!=AMA_ACCESS_RESUME))\n"
            "        return (AmaProjectResult){AMA_PROJECT_FAILED,ama_status_make(AMA_INVALID_STATE,NULL,0)};\n"
            "    host->executing=true; ama_project_owner=host;\n"
            "#define ama_world (host->world)\n#define ama_program (host->program)\n"
            "AmaHandle ama_root=host->root, ama_current=host->root;\n"
            "AmaPoolCell *ama_cell=NULL; uint64_t ama_return=0;\n"
            "AmaStatus ama_status=ama_status_success();\n"
            "AmaProjectOutcome ama_outcome=AMA_PROJECT_COMPLETED;\n"
            "if(!host->initialized) {\n"
            "    host->initialized=true;\n"
            "    ama_world=(AmaWorld){.types=ama_project_registry,\n"
            "        .type_count=sizeof(ama_project_registry)/sizeof(ama_project_registry[0]),.allocator=source_system_allocator()};\n"
            "    ama_program=(AmaProgram){.world=&ama_world,.types=ama_project_program_types,\n"
            "        .type_count=sizeof(ama_project_program_types)/sizeof(ama_project_program_types[0]),\n"
            "        .constants=ama_project_constants,.constant_count=%zu,\n"
            "        .locations=ama_project_locations,.location_count=sizeof(ama_project_locations)/sizeof(ama_project_locations[0])};\n"
            "    ama_world.report=ama_program_report; ama_world.report_context=&ama_program;\n"
            "    ama_status=ama_project_prepare_types(&ama_world);\n"
            "    if(ama_status.code==AMA_OK) ama_status=ama_program_start(&ama_program,UINT64_C(%zu),&ama_root);\n"
            "    host->root=ama_root; ama_current=ama_root;\n"
            "    if(ama_status.code!=AMA_OK) goto ama_project_finish;\n"
            "} else if(mode==AMA_ACCESS_ENTRY) {\n"
            "    ama_status=ama_program_cell(&ama_program,ama_root,&ama_cell);\n"
            "    if(ama_status.code==AMA_OK) ama_status=ama_service_access(&ama_cell->metadata.service,mode);\n"
            "    if(ama_status.code!=AMA_OK) goto ama_project_finish;\n"
            "    ama_cell->metadata.service.outgoing=ama_root;\n"
            "    ama_cell->metadata.service.outgoing_previous=ama_cell->metadata.service.activity;\n"
            "    ama_cell->metadata.service.activity=AMA_INSTANCE_ACQUIRED;\n"
            "    ama_status=ama_program_prepare(&ama_program,ama_root,&(AmaProgramInvocation){.mode=AMA_ACCESS_ENTRY});\n"
            "    ama_cell->metadata.service.outgoing=(AmaHandle){0};\n"
            "    if(ama_status.code!=AMA_OK) goto ama_project_finish;\n"
            "}\n"
            "ama_program.current=ama_current; ama_status=ama_program_cell(&ama_program,ama_current,&ama_cell);\n"
            "if(ama_status.code!=AMA_OK) goto ama_project_finish;\n"
            "if(mode==AMA_ACCESS_RESUME) {\n"
            "    ama_status=ama_service_access(&ama_cell->metadata.service,mode);\n"
            "    if(ama_status.code!=AMA_OK) goto ama_project_finish;\n"
            "    ama_return=ama_cell->metadata.service.resume.selector;\n"
            "}\n"
            "ama_cell->metadata.service.resume=(AmaResumePosition){0};\n"
            "ama_cell->metadata.service.activity=AMA_INSTANCE_RUNNING;\n"
            "ama_cell->metadata.service.return_link=(AmaReturnLink){.attached=true,.host=true};\n"
            "if(mode==AMA_ACCESS_RESUME) goto ama_project_resume;\n",
            scaffold->frontend->semantic.constant_count, codegen_type_id(scaffold, scaffold->selected)) >= 0;
}
