#include "codegen/emitter.h"

/* Entry existence and signature are validated by the project layer. */
void emit_program_entry_point(Emitter* emitter, const char* entry) {
    FILE* output = emitter->output;
    fputs("int main(void) {\n", output);
    emit_call_init(emitter, entry);
    fputs("    ", output);
    emit_module_name(output, entry);
    fputs("();\n    return 0;\n}\n", output);
}

void emit_program_prologue(FILE* output, const SymbolTable* symbols) {
    fputs("/* Generated by the Ama compiler. */\n", output);
    fputs("#include <stddef.h>\n#include <stdio.h>\n\n", output);
    for (uint32_t index = 0; index < symbols->symbol_count; index++) {
        const Symbol* symbol = &symbols->symbols[index];
        if (symbol->kind != SYMBOL_MODULE_ALIAS)
            fprintf(output, "static size_t symbol_%u;\n", symbol->symbol_id);
    }
    fputc('\n', output);
}
