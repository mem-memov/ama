#include "codegen/emitter.h"

/* Entry existence and signature are validated by the project layer. */
void backend_emit_main(Emitter* emitter, const char* entry) {
    FILE* out = emitter->out;
    fputs("int main(void) {\n", out);
    emit_call_init(emitter, entry);
    fputs("  ", out);
    emit_module_name(out, entry);
    fputs("();\n  return 0;\n}\n", out);
}

void backend_emit_prologue(FILE* out, const SymbolTable* symbols) {
    fputs("/* Generated by the Ama compiler. */\n", out);
    fputs("#include <stddef.h>\n#include <stdio.h>\n\n", out);
    for (uint32_t i = 0; i < symbols->count; i++) {
        const Symbol* symbol = &symbols->symbols[i];
        if (symbol->kind != SYM_ALIAS)
            fprintf(out, "static size_t v_%u;\n", symbol->id);
    }
    fputc('\n', out);
}
