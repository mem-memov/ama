#include "codegen/emitter.h"
#include <string.h>

/* Entry existence and signature are validated by the project layer. */
void emit_program_entry_point(Emitter* emitter, const char* entry) {
    emit_generated_location(emitter);
    fputs("int main(void) {\n", emitter->output);
    emit_call_init(emitter, entry);
    emit_call_exec(emitter, entry);
    fputs("    return 0;\n}\n", emitter->output);
}

static void emit_module_state(FILE* output, const SymbolTable* symbols, const char* path) {
    emit_source_label(output, path);
    fputs("typedef struct {\n", output);
    int field_count = 0;
    for (uint32_t index = 0; index < symbols->symbol_count; index++) {
        const Symbol* symbol = &symbols->symbols[index];
        if (symbol->kind != SYMBOL_MODULE_ALIAS && strcmp(symbol->module_path, path) == 0) {
            fputs("    ", output);
            emit_source_label(output, symbol->name);
            fputs("    size_t ", output);
            emit_generated_name(output, NAME_FIELD, path, symbol->name);
            fputs(";\n", output);
            field_count++;
        }
    }
    /* ISO C requires a nonempty structure even for a stateless module. */
    if (!field_count) fputs("    unsigned char unused;\n", output);
    fputs("} ", output);
    emit_state_type(output, path);
    fputs(";\nstatic ", output);
    emit_state_type(output, path);
    fputc(' ', output);
    emit_default_instance(output, path);
    fputs(";\n\n", output);
}

void emit_program_prologue(FILE* output, const SymbolTable* symbols, const Graph* graph) {
    fputs("/* Generated by the Ama compiler. */\n", output);
    fputs("#include <stddef.h>\n#include <stdio.h>\n\n", output);
    for (int index = 0; index < graph->node_count; index++)
        emit_module_state(output, symbols, graph->nodes[index].path);
}
