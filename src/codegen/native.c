#include "codegen/native.h"
#include <string.h>

static bool is_ascii_identifier_character(unsigned char character) {
    return (character >= 'a' && character <= 'z') ||
        (character >= 'A' && character <= 'Z') ||
        (character >= '0' && character <= '9') || character == '_';
}

bool native_function_name(const char* module_path, char* name, size_t capacity, Error* error) {
    int length = snprintf(name, capacity, "ama_native_%s", module_path);
    if (length < 0 || (size_t)length >= capacity)
        return error_set(error, ERROR_LIMIT, 0, "native function name is too long");
    for (char* character = name; *character; character++) {
        if (*character == '/') *character = '_';
        else if (!is_ascii_identifier_character((unsigned char)*character))
            return error_set(error, ERROR_INVALID, 0,
                "native module paths require ASCII letters, digits, underscores, and slashes");
    }
    return true;
}

bool validate_native_signature(SymbolTable* symbols, const char* module_path, Error* error) {
    char function_name[MAX_FILE_PATH_LENGTH];
    if (!native_function_name(module_path, function_name, sizeof(function_name), error)) return false;
    for (uint32_t index = 0; index < symbols->symbol_count; index++) {
        const Symbol* symbol = &symbols->symbols[index];
        if (strcmp(symbol->module_path, module_path) || symbol->kind == SYMBOL_MODULE_ALIAS) continue;
        for (const unsigned char* character = (const unsigned char*)symbol->name; *character; character++) {
            if (!is_ascii_identifier_character(*character))
                return error_set(error, ERROR_INVALID, 0,
                    "native parameter and result names require ASCII identifiers: '%s'", symbol->name);
        }
    }
    return true;
}

static void emit_signature(FILE* output, SymbolTable* symbols, const char* module_path, const char* name) {
    fprintf(output, "void %s(", name);
    int argument_count = 0;
    for (int group = 0; group < 2; group++) {
        SymbolKind kind = group == 0 ? SYMBOL_PARAMETER : SYMBOL_RESULT;
        for (int position = 0;; position++) {
            Symbol* symbol = find_symbol_by_position(symbols, module_path, position, kind);
            if (!symbol) break;
            if (argument_count++) fputs(", ", output);
            fprintf(output, group == 0 ? "size_t parameter_%s" : "size_t* result_%s", symbol->name);
        }
    }
    if (!argument_count) fputs("void", output);
    fputc(')', output);
}

bool emit_native_header(FILE* output, SymbolTable* symbols, const char* module_path, Error* error) {
    char name[MAX_FILE_PATH_LENGTH];
    if (!validate_native_signature(symbols, module_path, error) ||
        !native_function_name(module_path, name, sizeof(name), error)) return false;
    /* Preserve case: math/value and math/Value are different native modules. */
    fprintf(output, "/* Generated by Ama; do not edit. */\n#ifndef AMA_NATIVE_HEADER_%s\n#define AMA_NATIVE_HEADER_%s\n", name, name);
    fputs("#include <stddef.h>\n\n", output);
    emit_signature(output, symbols, module_path, name);
    fputs(";\n\n#endif\n", output);
    return true;
}

bool emit_native_stub(FILE* output, SymbolTable* symbols, const char* module_path, Error* error) {
    char name[MAX_FILE_PATH_LENGTH];
    if (!validate_native_signature(symbols, module_path, error) ||
        !native_function_name(module_path, name, sizeof(name), error)) return false;
    fputs("/* Created by Ama. Implement this file; it will not be overwritten. */\n", output);
    fprintf(output, "#include \"%s.h\"\n\n", name);
    fputs("#error \"Implement this native module and remove this directive\"\n\n", output);
    emit_signature(output, symbols, module_path, name);
    fputs(" {\n", output);
    for (uint32_t index = 0; index < symbols->symbol_count; index++) {
        const Symbol* symbol = &symbols->symbols[index];
        if (strcmp(symbol->module_path, module_path) || symbol->kind == SYMBOL_MODULE_ALIAS) continue;
        fprintf(output, "    (void)%s_%s;\n",
            symbol->kind == SYMBOL_PARAMETER ? "parameter" : "result", symbol->name);
    }
    fputs("}\n", output);
    return true;
}

bool emit_native_wrapper(Emitter* emitter, const char* module_path, Error* error) {
    char name[MAX_FILE_PATH_LENGTH];
    if (!native_function_name(module_path, name, sizeof(name), error)) return false;
    fprintf(emitter->output, "#include \"%s.h\"\n\nvoid ", name);
    emit_module_name(emitter->output, module_path);
    fprintf(emitter->output, "(void) {\n    %s(", name);
    int argument_count = 0;
    for (int group = 0; group < 2; group++) {
        SymbolKind kind = group == 0 ? SYMBOL_PARAMETER : SYMBOL_RESULT;
        for (int position = 0;; position++) {
            Symbol* symbol = find_symbol_by_position(emitter->symbols, module_path, position, kind);
            if (!symbol) break;
            if (argument_count++) fputs(", ", emitter->output);
            fprintf(emitter->output, group == 0 ? "symbol_%u" : "&symbol_%u", symbol->symbol_id);
        }
    }
    fputs(");\n}\n\n", emitter->output);
    return true;
}
