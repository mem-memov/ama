/**
 * @file
 * @brief Track exact compiler inputs and propagate change through explicit consumer dependencies.
 *
 * [DEP-03](../../../spec/implementation/compiler.md#dep-03) requires every contributing
 * input to invalidate its consumers; equality uses original bytes, never timestamps or hash guesses.
 */
#ifndef AMA_PROJECT_INPUTS_H
#define AMA_PROJECT_INPUTS_H
#include "project/dependencies/project.h"

/** Disjoint key domains prevent physical files, configuration, generated data and module consumers from aliasing. Component contract: [DEP-03](../../../spec/implementation/compiler.md#dep-03). */
typedef enum { PROJECT_INPUT_FILE, PROJECT_INPUT_CONFIGURATION,
    PROJECT_INPUT_GENERATED, PROJECT_INPUT_MODULE } ProjectInputKind;
/** Stable snapshot-owned node; clients construct dependencies through checked operations. Component contract: [DEP-03](../../../spec/implementation/compiler.md#dep-03). */
typedef struct ProjectInput ProjectInput;
/** Owner of copied configuration/generated bytes, loaded native files and graph storage.
 * Captured Ama/ABI text borrows the Project until snapshot destruction.
 * Component contract: [DEP-03](../../../spec/implementation/compiler.md#dep-03). */
typedef struct {
    SourceArena arena;
    SourceManager sources;
    ProjectInput *first;
    const char *failed_path;
    bool attempted;
    bool sealed;
    bool compared;
} ProjectInputs;

/** Initialize a mutable empty graph; allocator authority outlives destruction. Component contract: [DEP-03](../../../spec/implementation/compiler.md#dep-03). */
void project_inputs_init(ProjectInputs *, SourceAllocator);
/** Release all graph/private input owners before the borrowed captured Project. Component contract: [DEP-03](../../../spec/implementation/compiler.md#dep-03). */
void project_inputs_destroy(ProjectInputs *);
/** Copy one exact key/payload. Equal repeats share a node; unequal repeats reject without publication.
 * Module consumers require an empty payload. Output changes only on success.
 * Component contract: [DEP-03](../../../spec/implementation/compiler.md#dep-03). */
SourceStatus project_inputs_put(ProjectInputs *, ProjectInputKind, const char *,
    const unsigned char *, size_t, ProjectInput **);
/** Borrow an exact node during construction or inspection; absence returns null. Component contract: [DEP-03](../../../spec/implementation/compiler.md#dep-03). */
ProjectInput *project_inputs_find(const ProjectInputs *, ProjectInputKind, const char *);
/** Borrow the exact captured file bytes of a sealed graph; missing keys or an
 * unsealed graph return null, never reread the filesystem. The graph/source
 * owners outlive the view under [DEP-03](../../../spec/implementation/compiler.md#dep-03).
 */
const SourceText *project_inputs_content(const ProjectInputs *, ProjectInputKind, const char *);
/** Add one consumer-to-dependency edge, deduplicating repeats. Both nodes must belong to this live mutable graph. Component contract: [DEP-03](../../../spec/implementation/compiler.md#dep-03). */
SourceStatus project_inputs_depend(ProjectInputs *, ProjectInput *, ProjectInput *);
/** Capture a valid loaded closure and its exact root settings once into an empty graph.
 * Existing source/ABI bytes are borrowed; native C/header files load once per exact physical path.
 * Failure leaves owned partial storage, an unsealed graph and an optional owned failed_path.
 * The stable filesystem/root inventory must describe the supplied Project load.
 * Component contract: [DEP-03](../../../spec/implementation/compiler.md#dep-03). */
SourceStatus project_inputs_capture(ProjectInputs *, const Project *, const ModuleRoot *, size_t);
/** Finish construction; callers must have checked every builder result. Further mutation rejects. Component contract: [DEP-03](../../../spec/implementation/compiler.md#dep-03). */
void project_inputs_seal(ProjectInputs *);
/** Compute the least dependency closure of changed bytes/keys/edges against a sealed previous graph.
 * A null previous graph denotes an initial build. Requires sealed graphs, performs no allocation.
 * Component contract: [DEP-03](../../../spec/implementation/compiler.md#dep-03). */
SourceStatus project_inputs_compare(ProjectInputs *, const ProjectInputs *);
/** Query one compared node. False means absent/uncompared/invalid arguments and preserves output. Component contract: [DEP-03](../../../spec/implementation/compiler.md#dep-03). */
bool project_inputs_changed(const ProjectInputs *, ProjectInputKind, const char *, bool *);
#endif
